    ('H360_FINANCE', 'FAC-002', 'Finance: Northgate'),
    ('H360_FINANCE', 'FAC-003', 'Finance: Eastside');

-- H360_EXEC: all facilities
INSERT INTO HOSPITAL360_CUR.GOVERNANCE.ROLE_FACILITY_ACCESS (ROLE_NAME, FACILITY_ID, COMMENT)
SELECT 'H360_EXEC', FACILITY_ID, 'Executive access to all facilities'
FROM HOSPITAL360_CUR.OPERATIONS.DIM_FACILITY;

-- =============================================================================
-- SECTION 4: Attach Row-Access Policies to fact tables with DEPT_ID
-- =============================================================================
-- Note: RAPs are attached to tables that have DEPT_ID or FACILITY_ID columns

ALTER TABLE HOSPITAL360_CUR.CLINICAL.FCT_ENCOUNTER
  ADD ROW ACCESS POLICY HOSPITAL360_CUR.GOVERNANCE.RAP_DEPARTMENT ON (DEPT_ID);

ALTER TABLE HOSPITAL360_CUR.OPERATIONS.FCT_ADT_EVENT
  ADD ROW ACCESS POLICY HOSPITAL360_CUR.GOVERNANCE.RAP_DEPARTMENT ON (DEPT_ID);

ALTER TABLE HOSPITAL360_CUR.OPERATIONS.FCT_OR_CASE
  ADD ROW ACCESS POLICY HOSPITAL360_CUR.GOVERNANCE.RAP_FACILITY ON (FACILITY_ID);

ALTER TABLE HOSPITAL360_CUR.WORKFORCE.FCT_LABOR_HOUR
  ADD ROW ACCESS POLICY HOSPITAL360_CUR.GOVERNANCE.RAP_DEPARTMENT ON (DEPT_ID);

ALTER TABLE HOSPITAL360_CUR.OPERATIONS.FCT_BED_STATUS
  ADD ROW ACCESS POLICY HOSPITAL360_CUR.GOVERNANCE.RAP_DEPARTMENT ON (DEPT_ID);
